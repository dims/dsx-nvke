package main

import (
	"encoding/base64"
	"fmt"
	"strings"
)

const (
	// defaultStateDir is the folder of the cloud-init shim of the node image. The shim prints
	// the content of "status" (controller/hack/capd-kindest-node/scripts/cloud-init-status-shim),
	// and nico-sim writes the same file (controller/nico-sim/internal/container/docker.go:23-24).
	defaultStateDir = "/var/lib/nico-containers/cloud-init"

	// markerName is the file in the state folder that holds the ID of the machine whose
	// commands ran. The state folder is on the /var volume of the node, so the marker
	// lives as long as the node state and not as long as the pod.
	markerName = "nvke-lab-bootstrap-helper.machine"

	heredocEnd = "NVKE_HELPER_EOF" // not possible in base64 text
)

// scriptOptions are the inputs of the script that runs in the host pod.
type scriptOptions struct {
	MachineID   string // the UID of the Cluster API Machine
	StateDir    string
	WaitSystemd bool // stop with "notready" while systemd is not up
}

// buildApplyScript returns the shell script that applies one cloud-config in the pod.
// The script prints one line "RESULT <state> <mode> <detail>":
//
//	done first      the files are written, the commands ran, the status is "done"
//	done repeat     the commands of this machine ran before. Only files that differ are written
//	error first     a file or a command failed. The status is "error"
//	error repeat    an earlier run failed or did not end. The commands do not run again
//	notready -      systemd is not up. Nothing is changed
//
// The script holds the file contents, so the caller must not log it.
func buildApplyScript(opts scriptOptions, files []file, commands []string) string {
	var b strings.Builder
	b.WriteString(`#!/bin/sh
# Generated by nvke-lab-bootstrap-helper for one machine. It holds the file contents of a
# bootstrap Secret, so it removes itself first.
rm -f "$0"
set -eu
# Folders and files get the modes that cloud-init gives them: 0755 and 0644.
umask 022
`)
	fmt.Fprintf(&b, "machine_id=%s\n", singleQuote(opts.MachineID))
	fmt.Fprintf(&b, "dir=%s\n", singleQuote(opts.StateDir))
	fmt.Fprintf(&b, "marker=\"$dir/%s\"\n", markerName)
	b.WriteString(`status_file="$dir/status"
written=0
`)
	b.WriteString(`
# The same atomic write as nico-sim (docker.go:205-210, 240-249).
write_status() {
  status_tmp="$status_file.tmp.$$"
  printf '%s\n' "$1" >"$status_tmp"
  chmod 0644 "$status_tmp"
  mv -f "$status_tmp" "$status_file"
}

# put PATH MODE OWNER: install one file. The content is base64 text on stdin.
# cloud-init opens the path and writes, so a symbolic link stays and its target gets the
# content. The file appears with one rename, so a unit that starts now reads all of it or none.
put() {
  mkdir -p "$(dirname "$1")"
  put_real=$(readlink -f "$1")
  put_tmp="$put_real.nvke-helper.$$"
  if ! { (umask 077 && base64 -d >"$put_tmp") && chmod "$2" "$put_tmp" && chown "$3" "$put_tmp"; }; then
    rm -f "$put_tmp"
    echo "write_files: $1 failed" >&2
    return 1
  fi
  if [ -f "$put_real" ] && cmp -s "$put_tmp" "$put_real"; then
    rm -f "$put_tmp"
    chmod "$2" "$put_real"
    chown "$3" "$put_real"
  else
    mv -f "$put_tmp" "$put_real"
    written=$((written + 1))
  fi
}

install_files() {
  :
`)
	for _, f := range files {
		fmt.Fprintf(&b, "  put %s %s %s <<'%s'\n", singleQuote(f.Path), singleQuote(f.Mode), singleQuote(f.Owner), heredocEnd)
		b.WriteString(base64Lines(f.Content))
		b.WriteString(heredocEnd + "\n")
	}
	b.WriteString(`}

# The commands of this machine ran before, or started. They never run again. A new container
# has the /etc of the image, so write each file that is absent or differs.
if [ -f "$marker" ] && [ "$(cat "$marker")" = "$machine_id" ]; then
  install_files
  status=$(cat "$status_file" 2>/dev/null || true)
  case "$status" in
    done)
      echo "RESULT done repeat files_written=$written"
      ;;
    error)
      echo "RESULT error repeat files_written=$written: an earlier run for this machine failed, see $dir/output.log in the pod"
      ;;
    *)
      write_status error
      echo "RESULT error repeat files_written=$written: an earlier run for this machine stopped before its end (status '${status:-none}'), the commands do not run again"
      ;;
  esac
  exit 0
fi
`)
	if opts.WaitSystemd {
		b.WriteString(`
# First run for this machine: the commands use systemctl, so systemd must be up. The wrapper
# of the pod mounts the /var volume before it starts systemd. So this test also makes sure
# that the marker was read from the volume and not from the /var of the image.
if command -v systemctl >/dev/null 2>&1; then
  state=$(systemctl is-system-running 2>/dev/null || true)
  case "$state" in
    running | degraded) ;;
    *)
      echo "RESULT notready - systemd is ${state:-not up}"
      exit 0
      ;;
  esac
fi
`)
	}
	b.WriteString(`
# The order is the one of nico-sim (docker.go:136-198): status "running", the files, the
# commands, then "done" or "error".
mkdir -p "$dir"
old=$(cat "$marker" 2>/dev/null || true)
if [ -n "$old" ]; then
  echo "NOTE the state folder has the marker of another machine ($old), so the node state is not new"
fi
write_status running
printf '%s\n' "$machine_id" >"$marker.tmp.$$"
mv -f "$marker.tmp.$$" "$marker"
stage=write_files
trap 'write_status error; echo "RESULT error first files_written=$written: $stage failed"' EXIT
install_files
stage='the write of runcmd.sh'
`)
	fmt.Fprintf(&b, "(umask 077 && base64 -d >\"$dir/runcmd.sh\") <<'%s'\n", heredocEnd)
	b.WriteString(base64Lines([]byte(buildRuncmdScript(commands))))
	b.WriteString(heredocEnd + "\n")
	fmt.Fprintf(&b, `trap - EXIT
if detail=$(sh "$dir/runcmd.sh" "$status_file" </dev/null); then
  echo "RESULT done first files_written=$written commands=%d"
else
  code=$?
  [ "$(cat "$status_file" 2>/dev/null || true)" = error ] || write_status error
  echo "RESULT error first files_written=$written: ${detail:-runcmd.sh stopped} (exit code $code), see $dir/output.log in the pod"
fi
`, len(commands))
	return b.String()
}

// buildRuncmdScript returns the script that runs the runcmd list. The form is the one of
// nico-sim (docker.go:200-221): "set -eu", each command with "sh -lc", the output in
// output.log next to the status file, "done" at the end and "error" from an exit trap.
// The helper adds a counter. On a failure the script prints the number of the command to
// file descriptor 3, which is the standard output of the caller.
func buildRuncmdScript(commands []string) string {
	var b strings.Builder
	b.WriteString(`#!/bin/sh
# The runcmd list of the bootstrap Secret. Written by nvke-lab-bootstrap-helper.
set -eu
status_file="$1"
write_status() {
    status_tmp="${status_file}.tmp.$$"
    printf '%s\n' "$1" > "$status_tmp"
    chmod 0644 "$status_tmp"
    mv -f "$status_tmp" "$status_file"
}
n=0
`)
	fmt.Fprintf(&b, "trap 'write_status error; echo \"command $n of %d failed\" >&3' EXIT\n", len(commands))
	b.WriteString("exec 3>&1 >\"${status_file%/*}/output.log\" 2>&1\n")
	for i, command := range commands {
		// A command gets no copy of descriptor 3, so a process that it leaves behind does
		// not hold the caller.
		fmt.Fprintf(&b, "n=%d\nsh -lc %s 3>&-\n", i+1, singleQuote(command))
	}
	b.WriteString("write_status done\ntrap - EXIT\n")
	return b.String()
}

// execCommand is the command of the exec call. It reads exactly the bytes of the script
// from stdin into a file on /run (memory), checks the size and runs the file. The script
// is not an argument, so its content is in no process list and in no runtime log.
func execCommand(scriptLength int) []string {
	const receive = `f=$(mktemp /run/nvke-lab-bootstrap-helper.XXXXXX) || exit 97
head -c "$1" >"$f" || { rm -f "$f"; exit 97; }
[ "$(wc -c <"$f")" -eq "$1" ] || { rm -f "$f"; exit 98; }
exec sh "$f"`
	return []string{"sh", "-c", receive, "nvke-lab-bootstrap-helper", fmt.Sprint(scriptLength)}
}

// singleQuote is the quoting of nico-sim (docker.go:271-273).
func singleQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}

func base64Lines(content []byte) string {
	encoded := base64.StdEncoding.EncodeToString(content)
	var b strings.Builder
	for len(encoded) > 76 {
		b.WriteString(encoded[:76] + "\n")
		encoded = encoded[76:]
	}
	if encoded != "" {
		b.WriteString(encoded + "\n")
	}
	return b.String()
}
